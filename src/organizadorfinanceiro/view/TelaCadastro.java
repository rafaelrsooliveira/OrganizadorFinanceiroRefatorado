    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        UsuarioService service = new UsuarioService();
        try {
            // Converte a renda (aceita vírgula ou ponto)
            double renda = Double.parseDouble(
                    txtRendaMensal.getText().trim().replace(",", "."));

            // Monta o objeto
            Usuario novo = new Usuario(
                    txtNome.getText().trim(),
                    renda,
                    txtUsuario.getText().trim(),
                    txtSenha.getText().trim());

            // O Service valida tudo: campos vazios, senha curta, login duplicado...
            service.cadastrar(novo);

            JOptionPane.showMessageDialog(this,
                    "Usuário cadastrado com sucesso!",
                    "Sucesso", JOptionPane.INFORMATION_MESSAGE);

            new TelaLogin().setVisible(true);
            dispose();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Renda mensal deve ser um número válido.",
                    "Erro de formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

